import { test, expect } from '@playwright/test';
test.beforeEach(async({page})=>{await page.goto('/');});
test('source editing preserves live content, validates duplicate and publishes',async({page})=>{
  await page.getByRole('button',{name:'Add Knowledge Source'}).click();
  await page.getByLabel('Course Category',{exact:false}).selectOption('Soft Skills');
  await page.getByLabel('Course Title',{exact:false}).selectOption('c1');
  await page.getByLabel('Knowledge Content',{exact:false}).fill('New communication content.');
  await page.getByRole('button',{name:'Save and Preview'}).click();
  await expect(page.getByRole('alert')).toContainText('already has a knowledge source');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'Leadership Skills'});
  await row.getByRole('button',{name:'Edit source',exact:true}).click();
  await page.getByLabel('Knowledge Content',{exact:false}).fill('Leadership begins with trust and clear goals.');
  await page.getByRole('button',{name:'Save and Preview',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Preview AI Coach'})).toBeVisible();
  await page.getByRole('button',{name:'All Knowledge Sources'}).click();
  await expect(row).toContainText('Previous version live');
  await row.getByRole('button',{name:'Preview source'}).click();
  await page.getByRole('button',{name:'Publish',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Publish',exact:true}).click();
  await expect(page.getByRole('button',{name:'Published',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'All Knowledge Sources'}).click();
  await expect(row).toContainText('Published');
  await expect(row).not.toContainText('Previous version live');
});
test('deactivate and reactivate changes learner availability',async({page})=>{
  const row=page.getByRole('row').filter({hasText:'Leadership Skills'});
  await row.getByRole('button',{name:'Deactivate coach'}).click();
  await page.getByRole('button',{name:'Deactivate',exact:true}).click();
  await expect(row).toContainText('Inactive');
  await page.getByLabel('Preview role').selectOption('Learner');
  await page.locator('article').filter({hasText:'Leadership Skills'}).getByRole('button',{name:'Open Course'}).click();
  await expect(page.getByRole('button',{name:'Ask AI Coach'})).toHaveCount(0);
  await page.getByLabel('Preview role').selectOption('Admin');
  await row.getByRole('button',{name:'Reactivate coach'}).click();
  await page.getByRole('button',{name:'Reactivate',exact:true}).click();
  await expect(row).toContainText('Published');
});
test('learner chats start fresh and are visible only in admin report',async({page})=>{
  await page.getByLabel('Preview role').selectOption('Learner');
  await page.locator('article').filter({hasText:'Leadership Skills'}).getByRole('button',{name:'Open Course'}).click();
  await page.getByRole('button',{name:'Ask AI Coach'}).click();
  await page.getByLabel('Ask your coach').fill('What is leadership?');
  await page.getByRole('button',{name:'Send question'}).click();
  await expect(page.getByRole('log')).toContainText('Leadership is the ability');
  await page.getByRole('button',{name:'New Chat',exact:true}).click();
  await expect(page.getByRole('log')).not.toContainText('What is leadership?');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('tab',{name:'Knowledge Check'}).click();
  await page.getByRole('button',{name:'Ask AI Coach'}).click();
  await page.getByLabel('Ask your coach').fill('What is leadership?');
  await page.getByRole('button',{name:'Send question'}).click();
  await expect(page.getByRole('log')).toContainText("can't provide the answer to an active assessment");
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByLabel('Preview role').selectOption('Admin');
  await page.getByRole('button',{name:'Conversation History',exact:true}).click();
  await page.getByLabel('Filter course').selectOption('c2');
  await page.getByLabel('Search learner').fill('Kavya');
  await expect(page.getByRole('button',{name:'View',exact:true})).toHaveCount(2);
  await page.getByRole('button',{name:'View',exact:true}).first().click();
  await expect(page.getByText('Blocked',{exact:true})).toBeVisible();
  await page.getByLabel('Preview role').selectOption('Learner');
  await expect(page.getByRole('button',{name:'Conversation History',exact:true})).toHaveCount(0);
});
test('file extraction, failed processing and delete',async({page})=>{
  await page.getByRole('button',{name:'Add Knowledge Source'}).click();
  await page.getByLabel('Course Category',{exact:false}).selectOption('Technology');
  await page.getByLabel('Course Title',{exact:false}).selectOption('c9');
  await page.getByRole('radio',{name:'Upload document'}).check();
  await page.getByLabel('Knowledge document').setInputFiles({name:'excel.txt',mimeType:'text/plain',buffer:Buffer.from('Excel formulas help you calculate totals and averages.')});
  await page.getByRole('button',{name:'Save and Preview'}).click();
  await expect(page.getByRole('heading',{name:'Preview AI Coach'})).toBeVisible();
  await page.getByRole('button',{name:'All Knowledge Sources'}).click();
  const row=page.getByRole('row').filter({hasText:'Excel for Analysts'});
  await expect(row).toContainText('Draft');
  await row.getByRole('button',{name:'View source',exact:true}).click();
  await expect(page.getByText('Excel formulas help you calculate totals and averages.')).toBeVisible();
  await page.getByRole('button',{name:'Edit Source',exact:true}).click();
  await page.getByLabel('Knowledge document').setInputFiles({name:'excel.pdf',mimeType:'application/pdf',buffer:Buffer.from('not a PDF')});
  await page.getByRole('button',{name:'Save and Preview'}).click();
  await expect(page.getByText('Processing failed',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Preview Coach'})).toBeDisabled();
  await page.getByRole('button',{name:'All Knowledge Sources'}).click();
  await row.getByRole('button',{name:'Delete source'}).click();
  await page.getByRole('button',{name:'Delete',exact:true}).click();
  await expect(row).toHaveCount(0);
});
test('settings persist, report filters and mobile fit',async({page})=>{
  await page.getByRole('button',{name:'Coach Settings',exact:true}).click();
  await page.getByLabel('Coach Name',{exact:false}).fill('Learning Buddy');
  await page.getByRole('button',{name:'Save Changes'}).click();
  await page.reload();
  await page.getByRole('button',{name:'Coach Settings',exact:true}).click();
  await expect(page.getByLabel('Coach Name',{exact:false})).toHaveValue('Learning Buddy');
  await page.getByLabel('Preview role').selectOption('Admin');
  await page.getByRole('button',{name:'Conversation History',exact:true}).click();
  await page.getByLabel('Search learner').fill('no such person');
  await expect(page.getByText('No conversation records found.')).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('navigation',{name:'Mobile navigation'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
});
